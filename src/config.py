"""K230 运行配置。

API：不含硬件调用；仅用于配置 Sensor、Display、cv_lite 和 UART 的参数值。
硬件：Yahboom K230 12Pin 模块。
运行时：CanMV K230 Yahboom v1.8.0 MicroPython。
"""

# -----------------------------------------------------------------------------
# 摄像头配置
# -----------------------------------------------------------------------------
# 灰度A/B测试开关：
# True：Sensor直接输出灰度图，并在灰度帧上只绘制FPS和钢球框；
# False：使用RGB888检测，显示前转换成RGB565。
# 不在主循环里把RGB图转换成灰度，避免额外的整帧转换和内存开销。
BALL_GRAYSCALE_ENABLED = True

# 640x480适合当前阶段：钢球半径仍有约13-20 px，同时运算量低于高分辨率。
CAMERA_WIDTH = 640
CAMERA_HEIGHT = 480
CAMERA_HMIRROR = False
CAMERA_VFLIP = False
# CanMV 当前 API 使用 auto_exposure() 控制自动曝光。
# 不配置“自动增益”：官方当前接口只有部分传感器支持的 again() 手动模拟增益。
CAMERA_AUTO_EXPOSURE = True
CAMERA_WARMUP_MS = 1000





# 裁剪参数（相对于原始640x480图像）。
#
# 旧值y=208、height=64时，实测球心约y=254、半径13~20 px，钢球下沿
# 可能达到y=274，已经超出裁剪下边界y=271。霍夫圆缺少完整外轮廓时会
# 频繁丢检，因此上下各保留更充分余量。处理高度增加50%，预计FPS会从
# 约90下降，但仍明显高于闭环所需的50 Hz测量量级，实机结果需复测。
CROP_ENABLED = True
CROP_X = 0
CROP_Y = 200
CROP_WIDTH = 640
CROP_HEIGHT = 96


# -----------------------------------------------------------------------------
# LCD 配置
# -----------------------------------------------------------------------------
# 当前实机的Yahboom官方例程使用ST7701驱动默认尺寸，并能脱机显示。
# main.py因此不再给Display.init()强制传入width/height。
DISPLAY_TYPE = "ST7701"
DISPLAY_WIDTH = 800
DISPLAY_HEIGHT = 480
DISPLAY_TO_IDE = True

# 控制台每隔多少帧输出一次，避免 print 严重拖慢帧率。
CONSOLE_INTERVAL_FRAMES = 10

DEBUG_IMAGE_ENABLED = False
# 本阶段专用文件名，避免与后续钢球 Debug 图片混淆。
DEBUG_IMAGE_PATH = "/sdcard/ball_debug.jpg"
DEBUG_SAVE_INTERVAL_MS = 5000
GC_INTERVAL_FRAMES = 30

# -----------------------------------------------------------------------------
# UART：K230向STM32单向发送真实视觉测量
# -----------------------------------------------------------------------------
# 整体闭环联调阶段：启用K230->STM32单向视觉测量。
# 若需要重新做纯视觉性能基线，可临时改为False；其余代码无需删除。
UART_ENABLED = True
UART_ID = 1
UART_BAUDRATE = 115200
UART_TX_PIN = 9
UART_RX_PIN = 10

# -----------------------------------------------------------------------------
# STM32 -> K230 黑匣子数据记录（写入TF卡，不写K230内部Flash）
# -----------------------------------------------------------------------------
# STM32以50 Hz回传二进制状态帧（V2=64字节，V3=98字节控制量分解调试格式）。
# K230只负责校验并原样记录，不在实时循环里生成CSV字符串，避免格式化
# 和频繁小文件写入拖慢视觉。
TELEMETRY_LOG_ENABLED = True
TELEMETRY_LOG_PATH = "/sdcard/ball_run.bin"

# UART每次最多取256字节；日志累计16帧（16*64=1024字节）后才写一次TF卡。
# 在50 Hz回传频率下约0.32秒写一次，比逐帧write()稳定得多。
TELEMETRY_RX_BUFFER_SIZE = 256
TELEMETRY_WRITE_BUFFER_SIZE = 1024

# 每写满4个1 KB块（约1.28秒）执行一次文件系统同步。
# 脱机运行时通常只能直接断电，因此不能只依赖程序退出时的close()。
# 数值越小，断电时损失的数据越少，但TF卡同步造成的瞬时卡顿越频繁。
TELEMETRY_SYNC_INTERVAL_BLOCKS = 4

# 仅用于控制台低频显示记录状态，不影响二进制记录频率。
TELEMETRY_STATUS_INTERVAL_FRAMES = 300

# -----------------------------------------------------------------------------
# 机械模型参数预留（当前设备程序不使用）
# -----------------------------------------------------------------------------
# 这些数值只记录当前零位约定、人工安全范围和一级近似模型的粗测初值。
# 它们尚未通过正反向标定，不得直接作为闭环控制、限位保护或精确补偿依据。
SERVO_ZERO_DEG = 0.0
RAIL_ZERO_OFFSET_DEG = 0.0
SERVO_LIMIT_DEG = 90.0
MODEL_R_SERVO_CM = 1.5
MODEL_L_DRIVE_CM = 24.8

# -----------------------------------------------------------------------------
# 钢球静态检测配置（当前阶段使用）
# -----------------------------------------------------------------------------
# 当前钢球在深色Blob阈值下会与背景/阴影形成大连通区域，因此正式链路
# 使用已在Yahboom v1.8.0实机验证的霍夫圆检测。
# 使用裁剪图时，ROI坐标必须相对于裁剪后的640x96图像，而不是原图。
# 当前现场已把左边界扩展到x=10。检测ROI可以比软件安全区更宽：
# 这样球虽然已经越过安全线，K230仍可报告“看得见但不安全”。
BALL_ROI = (10, 0, 620, 96)
BALL_CIRCLE_DP = 1
BALL_CIRCLE_MIN_DIST = 30
BALL_CIRCLE_PARAM1 = 80
BALL_CIRCLE_PARAM2 = 20
BALL_CIRCLE_MIN_RADIUS = 8
BALL_CIRCLE_MAX_RADIUS = 35

# -----------------------------------------------------------------------------
# 钢球连续跟踪参数
# -----------------------------------------------------------------------------
# 首次找到多个圆且没有上一帧位置参考时，优先选择半径最接近17 px的圆。
# 17来自当前相机距离下多次静态实测的典型钢球半径，不是物理半径。
BALL_EXPECTED_RADIUS = 17

# 已经跟踪到钢球后，只接受距离上一帧不超过80 px的候选圆。
# 该限制用于排除突然跳到远处反光点；若高速滚动时连续丢球，可适当增大。
BALL_TRACK_MAX_JUMP_PX = 80

# 相邻有效帧的半径变化不能超过8 px，用于排除突然变大的反光圆。
# 日志中的正常半径主要为13～20 px，因此8 px保留了较宽余量。
BALL_TRACK_MAX_RADIUS_CHANGE = 8

# 连续3帧没有合格候选后，忘记旧位置并允许在全ROI重新捕获钢球。
# 在约90 FPS下对应约33 ms；超过该窗口才真正失球，窗口内改用预测位置。
BALL_TRACK_LOST_RESET_FRAMES = 3

# 速度外推预测参数（钢球检测的可信度门限）。
# 实际运行约90 FPS，每帧间隔约11 ms；正常滚动每帧只移动数像素，
# 因此检测圆心相对"上一帧位置+速度外推"的偏移超过GATE_PX就判为误检，
# 改用预测位置保持，不让单帧错误直接打进控制器。
BALL_PREDICT_GATE_PX = 20
# 速度外推的指数滤波系数；越大越相信当前帧的瞬时速度，越小越平滑。
BALL_PREDICT_VELOCITY_ALPHA = 0.40
# 估计速度的绝对值上限，px/s；防止单帧错误把速度估计打爆。
BALL_PREDICT_V_MAX_PX_S = 600

# 重新捕获确认：被追丢后，新候选必须连续 CONFIRM_FRAMES 帧在容差内一致
# 才正式接受，防止单个反光/背景圆在失球后直接成为新目标。
BALL_ACQUIRE_CONFIRM_FRAMES = 3
BALL_ACQUIRE_CONFIRM_TOLERANCE_PX = 12

# 一阶指数滤波系数：0.75表示新测量占75%，历史占25%。
# 数值越大响应越快但越抖；当前优先保证滚动跟踪的实时性。
BALL_FILTER_ALPHA = 0.20

# 2026-07-30标尺实测：轨道物理中心为x=314，作为控制零点。
# 画面右侧对应固定端，因此error_px = TARGET_X - ball_x：
#   error_px < 0 固定端；error_px = 0 中心；error_px > 0 舵机端。
BALL_TARGET_X = 314

# 实测钢球圆心可见范围约为x=22～622：
#   x=22约为-11.6 cm，x=622约为+11.8 cm。
# 当前把整段实测可见范围开放为控制区，避免球进入画面边缘后保护逻辑
# 提前撤销舵机控制；若后续发现边缘圆检测不稳定，再根据实机结果收紧。
BALL_SAFE_LEFT_X = 22
BALL_SAFE_RIGHT_X = 622
